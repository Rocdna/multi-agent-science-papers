"""Bundle Markdown notes and repository reading status for the static site."""

import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTES_ROOT = (ROOT / "notes").resolve()
paper_data = (ROOT / "index.html").read_text(encoding="utf-8")
paper_list = json.loads(re.search(r"const papers=(\[.*?\]);", paper_data, re.S).group(1))
papers_by_key = {paper["key"]: paper for paper in paper_list}
index = json.loads((NOTES_ROOT / "index.json").read_text(encoding="utf-8"))
bundled = {}
for paper_key, value in index.items():
    if paper_key not in papers_by_key:
        raise ValueError(f"Unknown note paper key: {paper_key}")
    # Accept the original one-note object as well as the new array format.
    entries = [value] if isinstance(value, dict) else value
    if not isinstance(entries, list):
        raise ValueError(f"Notes for {paper_key} must be an object or array")
    notes, seen_ids = [], set()
    for metadata in entries:
        note_id = metadata.get("id", "main")
        if not isinstance(note_id, str) or not re.fullmatch(r"[a-z0-9][a-z0-9_-]{0,63}", note_id):
            raise ValueError(f"Invalid note id for {paper_key}: {note_id}")
        if note_id in seen_ids:
            raise ValueError(f"Duplicate note id for {paper_key}: {note_id}")
        seen_ids.add(note_id)
        date.fromisoformat(metadata["updated"])
        if not isinstance(metadata["title"], str) or not metadata["title"].strip():
            raise ValueError(f"Missing note title for {paper_key}/{note_id}")
        note_path = (ROOT / metadata["file"]).resolve()
        if not note_path.is_relative_to(NOTES_ROOT) or note_path.suffix.lower() != ".md":
            raise ValueError(f"Invalid note path: {metadata['file']}")
        notes.append({
            **metadata,
            "id": note_id,
            "paper": {
                "name": papers_by_key[paper_key]["name"],
                "title": papers_by_key[paper_key]["title"],
                "url": papers_by_key[paper_key]["paper"],
            },
            "markdown": note_path.read_text(encoding="utf-8"),
        })
    if notes:
        bundled[paper_key] = sorted(notes, key=lambda note: note["updated"], reverse=True)

paper_keys = set(papers_by_key)
entries = json.loads((ROOT / "data" / "reading-status.json").read_text(encoding="utf-8"))
statuses = {}
for paper_key, entry in entries.items():
    if paper_key not in paper_keys:
        raise ValueError(f"Unknown paper key: {paper_key}")
    status = entry["status"]
    if status not in {"unread", "reading", "read"}:
        raise ValueError(f"Invalid reading status for {paper_key}: {status}")
    statuses[paper_key] = status
(ROOT / "assets" / "notes-data.js").write_text(
    "// Generated by scripts/build_notes.py; edit notes/*.md instead.\n"
    + "const literatureNotes = "
    + json.dumps(bundled, ensure_ascii=False, indent=2)
    + ";\n",
    encoding="utf-8",
)
(ROOT / "assets" / "reading-data.js").write_text(
    "// Generated by scripts/build_notes.py; edit data/reading-status.json instead.\n"
    + "const literatureReadingStatuses = "
    + json.dumps(statuses, ensure_ascii=False, indent=2)
    + ";\n",
    encoding="utf-8",
)
print(f"Bundled {sum(len(notes) for notes in bundled.values())} note(s) for {len(bundled)} paper(s).")
print(f"Bundled {len(statuses)} reading status record(s).")
