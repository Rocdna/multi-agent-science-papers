// Stage only public files; never upload the workspace, credentials or dependencies.
import {readFile, writeFile, mkdir, cp, readdir, rm} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const html = await readFile(path.join(root, 'index.html'), 'utf8');
const papers = JSON.parse(html.match(/const papers=(\[.*?\]);/s)[1]);
const catalog = papers.map(({key, name, title, year, topic}) => ({key, name, title, year, topic}));
if (new Set(catalog.map(paper => paper.key)).size !== catalog.length) throw new Error('Duplicate paper keys');
await mkdir(path.join(root, 'worker'), {recursive: true});
await writeFile(path.join(root, 'worker/catalog.json'), JSON.stringify(catalog, null, 2) + '\n');
await writeFile(path.join(root, 'assets/paper-catalog.js'),
  '// Generated by scripts/build_site.mjs from the public literature catalog.\n'
  + 'const literaturePaperCatalog = ' + JSON.stringify(catalog, null, 2).replaceAll('<', '\\u003c') + ';\n');
const output = path.resolve(root, 'dist');
if (path.dirname(output) !== path.resolve(root) || path.basename(output) !== 'dist') {
  throw new Error('Unexpected output directory');
}
await rm(output, {recursive: true, force: true});
await mkdir(output, {recursive: true});
for (const directory of ['assets', 'vendor', 'notes', 'admin']) {
  await cp(path.join(root, directory), path.join(output, directory), {
    recursive: true,
    filter: source => !['.DS_Store', 'Thumbs.db', '__pycache__'].includes(path.basename(source)),
  });
}
for (const entry of await readdir(root)) {
  if (/\.(html|ico|png)$/.test(entry) || ['ICON_CREDITS.md', 'Multi-agent_AI材料文献总结.md'].includes(entry)) {
    await cp(path.join(root, entry), path.join(output, entry));
  }
}
console.log(`Built public site and ${catalog.length} catalog entries in dist/.`);
