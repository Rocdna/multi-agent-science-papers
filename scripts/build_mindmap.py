"""Bundle the manually maintained mind map for static and file:// reading.

Run from any directory: python scripts/build_mindmap.py
The browser importer performs the same data validation before editing.
"""
import json
import re
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "mindmaps/library.json"
TARGET = ROOT / "assets/mindmap-data.js"
MAX_FILE = 32 * 1024 * 1024


def validate(document):
    if document.get("format") != "paper-mindmap" or document.get("version") not in (1, 2):
        raise ValueError("Expected paper-mindmap version 1 or 2")
    data = document["data"]
    if data.get("arrows") or data.get("summaries"):
        raise ValueError("Arrows and summaries are not supported")
    ids = set()

    def walk(node, depth=0):
        node_id = node["id"]
        if not isinstance(node_id, str) or not re.fullmatch(r"[a-zA-Z0-9_-]{1,80}", node_id) or node_id in ids:
            raise ValueError("Invalid or duplicate node ID")
        ids.add(node_id)
        if len(ids) > 500 or depth > 40:
            raise ValueError("Maximum 500 nodes / 40 levels")
        if not isinstance(node["topic"], str) or len(node["topic"]) > 4000:
            raise ValueError("Invalid node topic")
        if node.get("hyperLink"):
            url = urlsplit(node["hyperLink"])
            if url.scheme not in ("http", "https") or not url.netloc:
                raise ValueError("Node links must use http(s)")
        if node.get("image"):
            image = node["image"]
            if not re.fullmatch(r"data:image/(png|jpeg|webp);base64,[A-Za-z0-9+/]+={0,2}", image["url"]):
                raise ValueError("Images must be embedded PNG, JPEG or WebP")
            if not 20 <= image["width"] <= 720 or not 10 <= image["height"] <= 1800:
                raise ValueError("Invalid image display dimensions")
        # Reject renderer instructions that the browser importer would discard.
        allowed = {"id", "topic", "expanded", "children", "direction", "hyperLink", "branchColor", "image", "style"}
        if set(node) - allowed:
            raise ValueError(f"Unsupported node properties: {set(node) - allowed}")
        for child in node.get("children", []):
            walk(child, depth + 1)

    walk(data["nodeData"])
    items = data.get("canvasItems", [])
    if not isinstance(items, list):
        raise ValueError("Invalid canvas items")
    for item in items:
        for coordinate in ("x", "y"):
            value = item[coordinate]
            if not isinstance(value, (int, float)) or not -100000 <= value <= 100000:
                raise ValueError("Invalid canvas position")
        if item["node"].get("children"):
            raise ValueError("Canvas elements must be individual text/image topics")
        walk(item["node"])
    return len(ids)


def main():
    if SOURCE.stat().st_size > MAX_FILE:
        raise ValueError("Mind map exceeds 32 MB")
    document = json.loads(SOURCE.read_text(encoding="utf-8-sig"))
    count = validate(document)
    payload = json.dumps(document, ensure_ascii=False, separators=(",", ":"))
    # Escape script delimiters for safe reuse if this bundle is ever inlined.
    payload = payload.replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    TARGET.write_text("/* Generated by scripts/build_mindmap.py; edit mindmaps/library.json. */\nconst publishedMindmap=" + payload + ";\n", encoding="utf-8", newline="\n")
    print(f"Built {TARGET.relative_to(ROOT)} ({count} nodes)")


if __name__ == "__main__":
    main()
